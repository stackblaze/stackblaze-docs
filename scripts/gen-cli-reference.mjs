// Generates content/docs/cli/reference/*.mdx from the released CLI's own
// `--help` output — nothing is written by hand. Re-run after a CLI release:
//   node scripts/gen-cli-reference.mjs /path/to/stackblaze
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const BIN = process.argv[2] ?? 'stackblaze';
const OUT = path.resolve(import.meta.dirname, '../content/docs/cli/reference');
// Help text never depends on the account; run it signed out and offline-safe.
const HOME = fs.mkdtempSync('/tmp/sbhelp-');
// The CLI hides the `functions` and `sandboxes` groups from `--help` until it has
// fetched the platform's feature flags (GET /api/features) and cached them. Both
// are on in production, so seed that cache for the public API (the URL a signed-out
// CLI uses) instead of signing in. Drop a key here if production switches it off.
const LISTED_FEATURES = { functions: true, sandboxes: true };
const FEATURES_CACHE = path.join(HOME, 'features.json');
fs.writeFileSync(
  FEATURES_CACHE,
  JSON.stringify({ 'https://api.stackblaze.cloud': { ...LISTED_FEATURES, fetchedAt: Date.now() } }),
);
const env = {
  ...process.env,
  NO_COLOR: '1',
  STACKBLAZE_TOKEN: '',
  STACKBLAZE_API_URL: '',
  STACKBLAZE_FEATURES_CACHE: FEATURES_CACHE,
  HOME,
};

function help(args) {
  try {
    return execFileSync(BIN, [...args, '--help'], { encoding: 'utf8', env, timeout: 20000 }).trimEnd();
  } catch (e) {
    return String(e.stdout || '').trimEnd();
  }
}

/** Subcommand names listed under "Commands:" (clap- or commander-style). */
function subcommands(text) {
  const m = text.split(/\n(?:Commands|Subcommands):\n/)[1];
  if (!m) return [];
  const names = [];
  for (const line of m.split('\n')) {
    if (/^\S/.test(line)) break; // next section
    const name = line.match(/^ {2}([a-z][a-z0-9-]*)/)?.[1];
    if (name && name !== 'help') names.push(name);
  }
  return names;
}

// Commands for features switched off on production (GET /api/addons/access → disabled:
// KuberoWaf, and no object storage). They stay out of the docs until they ship.
const OFF_GROUPS = new Set(['waf']);
const OFF_SUBCOMMANDS = new Set(['addons export']);
const NOTES = {
  'addons import': 'Importing from an `s3://` source needs a Storage bucket add-on, which isn\'t available yet.',
};

const version = execFileSync(BIN, ['--version'], { encoding: 'utf8', env }).trim();
const top = help([]);
const groups = subcommands(top).filter((g) => !OFF_GROUPS.has(g));
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const fence = (t) => '```text\n' + t.replace(/```/g, "'''") + '\n```';
// The first paragraph after "Usage:", with its wrapped lines joined.
const summary = (t) => {
  const lines = t.split('\n');
  let i = lines.findIndex((l) => l.trim() && !l.startsWith('Usage:'));
  const out = [];
  for (; i >= 0 && i < lines.length && lines[i].trim(); i++) out.push(lines[i].trim());
  return out.join(' ');
};

for (const g of groups) {
  const gh = help([g]);
  const subs = subcommands(gh);
  let body = `---\ntitle: stackblaze ${g}\ndescription: ${JSON.stringify(summary(gh)).slice(1, -1).replace(/:/g, ' -')}\n---\n\n`;
  body += `{/* Generated by scripts/gen-cli-reference.mjs from \`stackblaze ${g} --help\` (CLI ${version}). Do not edit. */}\n\n`;
  body += fence(gh) + '\n';
  for (const s of subs) {
    if (OFF_SUBCOMMANDS.has(`${g} ${s}`)) continue;
    const sh = help([g, s]);
    body += `\n## ${g} ${s}\n\n${fence(sh)}\n`;
    if (NOTES[`${g} ${s}`]) body += `\n${NOTES[`${g} ${s}`]}\n`;
    for (const s2 of subcommands(sh)) body += `\n### ${g} ${s} ${s2}\n\n${fence(help([g, s, s2]))}\n`;
  }
  fs.writeFileSync(path.join(OUT, `${g}.mdx`), body);
}

fs.writeFileSync(
  path.join(OUT, 'index.mdx'),
  `---\ntitle: CLI reference\ndescription: Every stackblaze command, from the CLI's own help (version ${version}).\n---\n\n` +
    `{/* Generated by scripts/gen-cli-reference.mjs. Do not edit. */}\n\n` +
    `Generated from \`stackblaze --help\` on CLI ${version}.\n\n` + fence(top) + '\n',
);
fs.writeFileSync(path.join(OUT, 'meta.json'), JSON.stringify({ title: 'Command reference', defaultOpen: false, pages: ['index', ...groups] }, null, 2) + '\n');
console.log(`${groups.length} command pages, CLI ${version}`);
